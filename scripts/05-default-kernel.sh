#!/usr/bin/env bash
#
# 05-default-kernel.sh — boot linux-surface by default
#
#     bash scripts/05-default-kernel.sh          promote linux-surface
#     bash scripts/05-default-kernel.sh --undo   put it back
#
# Until you run this, the boot menu still selects your distribution kernel
# when the countdown runs out — which means no touchscreen unless you catch
# the menu and pick manually every time.
#
# Only do this once linux-surface has booted cleanly several times. Your
# distribution kernel stays directly below it in the menu either way.
#
# HOW, and why not the obvious way:
#
# Do NOT edit `default_entry` in limine.conf. That file is regenerated by
# limine-entry-tool on every kernel update and your edit disappears — quietly,
# and you find out at the worst moment.
#
# Instead we change BOOT_ORDER through a drop-in, which is configuration
# rather than generated output. limine-entry-tool then places linux-surface
# first by itself, and default_entry follows along.
#
# Part of https://github.com/Overpaul-Ops/surface-book-2-omarchy — MIT licensed.

set -euo pipefail

DROPIN="/etc/limine-entry-tool.d/zz-surface-first.conf"
UNDO=0
[ "${1:-}" = "--undo" ] && UNDO=1

say()  { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }
ok()   { printf '    \033[1;32mOK\033[0m    %s\n' "$*"; }
warn() { printf '    \033[1;33mWARN\033[0m  %s\n' "$*"; }
die()  { printf '\n\033[1;31mABORT: %s\033[0m\n' "$*" >&2; exit 1; }

[ "$(id -u)" -ne 0 ] || die "Run as your normal user, not with sudo."
command -v limine-update >/dev/null || die "limine-update not found. This step is Limine-specific."

# ---------------------------------------------------------------------------
if [ "$UNDO" = "1" ]; then
    say "Undo: back to the distribution kernel as default"
    [ -f "$DROPIN" ] || die "$DROPIN does not exist — nothing to undo."
    sudo rm -f "$DROPIN"
    ok "removed $DROPIN"
    sudo limine-update || die "limine-update failed"
    sudo grep -nE '^\s*(//|default_entry)' /boot/limine.conf | sed 's/^/    /'
    printf '\nDone. Verify the order above, then reboot.\n'
    exit 0
fi

# ---------------------------------------------------------------------------
say "Step 0: prerequisites"
# ---------------------------------------------------------------------------

# Which installed kernel is the surface one?
SURFACE=""
for d in /usr/lib/modules/*/; do
    [ -e "${d}pkgbase" ] || continue
    pb="$(cat "${d}pkgbase")"
    case "$pb" in *surface*) SURFACE="$pb" ;; esac
done
[ -n "$SURFACE" ] || die "No linux-surface kernel installed. Run scripts/02-kernel-install.sh first."
ok "surface kernel package: $SURFACE"

case "$(uname -r)" in
    *surface*) ok "you are running it right now" ;;
    *) warn "You are NOT currently running the surface kernel."
       warn "Promoting a kernel you have never successfully booted is a bad idea."
       printf '\n    Continue anyway? Type exactly  yes  : '
       read -r a; [ "$a" = "yes" ] || die "Stopped." ;;
esac

# How many distinct boots does the journal remember? Not proof, but a hint.
BOOTS=$(journalctl --list-boots --no-pager 2>/dev/null | grep -c '^' || echo 0)
[ "$BOOTS" -gt 1 ] && ok "journal remembers $((BOOTS-1)) previous boot(s)"

# ---------------------------------------------------------------------------
say "Step 1: current boot order"
# ---------------------------------------------------------------------------

# Later files win, so read them in the same order limine-entry-tool does.
CURRENT=""
for f in /etc/limine-entry-tool.conf /etc/limine-entry-tool.d/*.conf /etc/default/limine; do
    [ -r "$f" ] || continue
    # `|| true` is not decoration: grep exits 1 when a file has no BOOT_ORDER,
    # pipefail passes that to the assignment, and set -e would abort the whole
    # script on the first config file that simply does not set it.
    v=$(grep -hE '^[[:space:]]*BOOT_ORDER=' "$f" 2>/dev/null | tail -1 | sed -E 's/^[^=]*=//; s/^"//; s/"$//' || true)
    [ -n "$v" ] && { CURRENT="$v"; SRC="$f"; }
done

if [ -z "$CURRENT" ]; then
    warn "No BOOT_ORDER found anywhere. Using a sensible default."
    CURRENT="*, *fallback, Snapshots"
    SRC="(none)"
fi
echo "    from: $SRC"
echo "    now:  $CURRENT"

# ---------------------------------------------------------------------------
say "Step 2: new boot order"
# ---------------------------------------------------------------------------

# Drop any existing mention of the surface kernel, then put it in front.
# Keeping the rest untouched means the distribution kernel stays right below.
# `|| true` again: if BOOT_ORDER contained nothing but the surface kernel,
# grep -v would output nothing and exit 1.
REST=$(printf '%s' "$CURRENT" \
    | tr ',' '\n' \
    | sed -E 's/^[[:space:]]+//; s/[[:space:]]+$//' \
    | grep -vx "$SURFACE" \
    | grep -vx "${SURFACE}\*" \
    | paste -sd ',' - \
    | sed 's/,/, /g' || true)

[ -n "$REST" ] || REST="*, *fallback, Snapshots"
NEW="${SURFACE}, ${REST}"
echo "    new:  $NEW"
echo
echo "    Your distribution kernel keeps its place directly after it, so the"
echo "    menu entry you have been picking manually is still one key away."

# ---------------------------------------------------------------------------
say "Step 3: write the drop-in"
# ---------------------------------------------------------------------------

sudo tee "$DROPIN" >/dev/null <<EOF_DROPIN
# Boot the linux-surface kernel by default.
#
# Written by scripts/05-default-kernel.sh from
# https://github.com/Overpaul-Ops/surface-book-2-omarchy
#
# This is a drop-in, not an edit of limine.conf: limine-entry-tool regenerates
# limine.conf on every kernel update, so an edit there would be lost. A
# drop-in is configuration and survives.
#
# Undo:  sudo rm $DROPIN && sudo limine-update
BOOT_ORDER="$NEW"
EOF_DROPIN
ok "$DROPIN"

# ---------------------------------------------------------------------------
say "Step 4: regenerate the boot menu"
# ---------------------------------------------------------------------------
echo "    limine-update must run for the drop-in to take effect. Without it"
echo "    the new order only applies after the next kernel update, which is a"
echo "    confusing way to find out it did not work."
echo

sudo limine-update || die "limine-update failed. Remove $DROPIN and try again."
ok "boot menu regenerated"

# ---------------------------------------------------------------------------
say "Step 5: verify BEFORE rebooting"
# ---------------------------------------------------------------------------

echo "    --- entries, in menu order ---"
sudo grep -nE '^[[:space:]]*(//|///|////|default_entry)' /boot/limine.conf | sed 's/^/      /'
echo
echo "    --- kernel command lines ---"
sudo grep -cE '^[[:space:]]*cmdline:.*cryptdevice=' /boot/limine.conf \
    | sed 's/^/      entries with cryptdevice=: /'
sudo grep -cE '^[[:space:]]*cmdline:' /boot/limine.conf \
    | sed 's/^/      entries total:            /'

if [ -x /usr/local/bin/surface-health-check ]; then
    echo
    sudo /usr/local/bin/surface-health-check || true
fi

# ---------------------------------------------------------------------------
say "Done — check the order above, then reboot"
# ---------------------------------------------------------------------------
cat <<EOF_SUMMARY

    WHAT TO CHECK:

      1. Is //${SURFACE} now listed FIRST?
      2. Is your distribution kernel still listed, right after it?
      3. Do the two numbers above match? Every entry must carry
         cryptdevice= or it will not unlock an encrypted disk.

    Then reboot and let the countdown run out. It should land on
    ${SURFACE} by itself.

    If it does not, or if something is wrong: press an arrow key at the
    menu and pick your distribution kernel. Then:

        bash scripts/05-default-kernel.sh --undo

    THE MENU COUNTDOWN is a few seconds by default. To change it, set a
    timeout in /boot/limine.conf:

        timeout: 10

    Note that limine-entry-tool may rewrite that file; if the setting does
    not stick, it is not worth fighting — an arrow key stops the countdown
    at any point.

EOF_SUMMARY
